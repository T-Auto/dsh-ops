/**
 * The `paged` fixture family: one long log file whose answer line sits beyond the
 * first page, for the V4 paged-cursor behavior task (#993).
 *
 * The shape is the point, not the content: a 600-line file read at the default
 * 200-line page size puts the marked line on page 2, so a trajectory must continue
 * at the envelope's nextOffset instead of re-reading page 1 or stopping early.
 * The marker token appears exactly once and every other payload is lowercase words
 * plus lowercase hex, so a wrong guess cannot pass and the exported answer is
 * recomputable from the bytes alone.
 *
 * @module dsh-ops/bench/fixtures/paged
 */

import { hexRun, mulberry32, pad, pick, WORDS } from './internal.mjs'

/**
 * `pagedLog` — one log file with exactly one marked line at a chosen position.
 * @param {{seed?: number, lines?: number, markerAt?: number}} params - the shape of the log.
 * @returns {{files: {path: string, content: string}[], exports: {answer: string, markerLine: number, markerText: string, totalLines: number}}} the fixture.
 */
export function pagedLog(params = {}) {
  const seed = params.seed ?? 41
  const lines = Math.max(120, params.lines ?? 600)
  const markerAt = params.markerAt ?? 350
  if (!Number.isInteger(markerAt) || markerAt < 2 || markerAt > lines) {
    throw new RangeError('markerAt must be an integer line index between 2 and lines')
  }
  const next = mulberry32(seed)
  const levels = ['INFO', 'INFO', 'DEBUG', 'INFO', 'WARN']
  const rows = []
  const stamp = (index) => '2025-03-' + pad((index % 28) + 1, 2) + 'T' + pad(index % 24, 2) + ':' + pad(index % 60, 2) + ':' + pad((index * 7) % 60, 2) + 'Z'
  for (let index = 1; index <= lines; index += 1) {
    const payload = pick(next, WORDS) + ' ' + pick(next, WORDS) + ' ' + hexRun(next, 8).toLowerCase()
    rows.push(pick(next, levels) + '|' + stamp(index) + '|' + payload)
  }
  const markerText = 'TARGET-' + hexRun(next, 8).toUpperCase() + ' ' + pick(next, WORDS) + ' ' + pick(next, WORDS)
  rows[markerAt - 1] = 'WARN|' + stamp(markerAt) + '|' + markerText
  const content = rows.join('\n') + '\n'
  // The token must be unique in the bytes, or the exported answer would be a lie.
  if (content.split('TARGET-').length !== 2) throw new Error('the TARGET marker must appear exactly once in the log')
  return {
    files: [{ path: 'logs/stream.log', content }],
    exports: { answer: markerAt + ' ' + markerText, markerLine: markerAt, markerText, totalLines: lines },
  }
}

/**
 * Recompute `pagedLog`'s exports from the generated bytes.
 * @param {{path: string, content: string}[]} files - the generated tree.
 * @returns {object} the recomputed expectation.
 * @throws {Error} when the log file is missing or the marker is not unique.
 */
export function derivePagedLog(files) {
  const file = files.find((entry) => entry.path === 'logs/stream.log')
  if (file === undefined) throw new Error('derivePagedLog: logs/stream.log is missing')
  const rows = file.content.replace(/\n$/, '').split('\n')
  const marked = rows.map((row, index) => (row.includes('TARGET-') ? index : -1)).filter((index) => index >= 0)
  if (marked.length !== 1) throw new Error('derivePagedLog: the TARGET marker must appear exactly once, found ' + marked.length)
  const markerLine = marked[0] + 1
  const markerText = rows[marked[0]].split('|')[2]
  return { answer: markerLine + ' ' + markerText, markerLine, markerText, totalLines: rows.length }
}
