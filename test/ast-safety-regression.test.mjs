import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { enumerate, clearEnumCache, inprocRefactor, inprocLocate } = require('../lib/ast/inproc.cjs');
const { checkedWrite, verifySnapshot } = require('../lib/ast/safe-write.cjs');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ptc-safety-'));
let checks=0;
const check=(name,fn)=>{fn(); checks++; console.log('PASS '+name);};
try {
  const a=path.join(dir,'a'), b=path.join(dir,'b'); fs.mkdirSync(a); fs.mkdirSync(b);
  for (const root of [a,b]) for(let i=0;i<5;i++) fs.writeFileSync(path.join(root,`${i}.ts`),'function f(){return true;}\n');
  const opts={cwd:dir,strategy:'walk',limit:2};
  clearEnumCache();
  const small=enumerate([a,b],new Set(['.ts']),opts);
  check('global cap and truthful truncation',()=>{assert.equal(small.files.length,2);assert.equal(small.truncated,true);});
  const hit=enumerate([a,b],new Set(['.ts']),opts);
  check('cached truncation',()=>{assert.equal(hit.cached,true);assert.equal(hit.truncated,true);});
  const large=enumerate([a,b],new Set(['.ts']),{...opts,limit:20});
  check('cap participates in cache key',()=>{assert.equal(large.files.length,10);assert.equal(large.truncated,false);});
  hit.files.length=0;
  check('cache arrays cannot be poisoned',()=>assert.equal(enumerate([a,b],new Set(['.ts']),opts).files.length,2));
  const file=path.join(dir,'change.ts'); fs.writeFileSync(file,'function f(){return true;}\n');
  const before=fs.readFileSync(file);
  check('changed snapshot rejected',()=>assert.throws(()=>verifySnapshot(file,Buffer.from('stale')),/发生变化/));
  fs.writeFileSync(file+'.ops-ast.lock','occupied');
  check('cooperative lock rejected',()=>assert.throws(()=>checkedWrite(file,before,'changed'),e=>e.code==='E_INPROC_LOCKED'));
  check('failed write retains source',()=>assert.deepEqual(fs.readFileSync(file),before));
  check('invalid mode rejected before write',()=>assert.equal(inprocRefactor({file,pattern:'return $A',rewrite:'return false',mode:'typo'},dir).code,'E_INPROC_ARGUMENT'));
  check('invalid limit rejected',()=>assert.equal(inprocRefactor({file,pattern:'return $A',rewrite:'return false',limit:NaN},dir).code,'E_INPROC_ARGUMENT'));
  check('unbound multi metavariable rejected',()=>assert.equal(inprocRefactor({file,pattern:'return $A',rewrite:'return [$$$MISSING]'},dir).code,'E_INPROC_TEMPLATE'));
  const bad=path.join(dir,'bad.ts'); fs.writeFileSync(bad,Buffer.concat([before,Buffer.from([0xff])]));
  check('invalid UTF8 rejected',()=>assert.equal(inprocRefactor({file:bad,pattern:'return $A',rewrite:'return false'},dir).code,'E_INPROC_ENCODING'));
  const multi=path.join(dir,'multi');fs.mkdirSync(multi);
  const first=path.join(multi,'a.ts'),second=path.join(multi,'b.ts');
  fs.writeFileSync(first,'function f(){return true;}\n');fs.writeFileSync(second,'function f(){return true;}\nfunction f(){return false;}\n');
  const outcome=inprocRefactor({roots:[multi],strategy:'walk',symbol:'f',limit:2,pattern:'return $A',rewrite:'return false;'},dir);
  check('all candidates audited before writing',()=>{assert.equal(outcome.code,'E_INPROC_SYMBOL_AMBIGUOUS');assert.match(fs.readFileSync(first,'utf8'),/return true/);});
  const link=path.join(dir,'hard.ts');fs.linkSync(file,link);
  check('hardlink replacement refused',()=>assert.throws(()=>checkedWrite(link,before,'new'),e=>e.code==='E_INPROC_FILE_TYPE'));
  check('non-null object validation',()=>assert.equal(inprocRefactor(null,dir).code,'E_INPROC_ARGUMENT'));
  check('locate symbol validation',()=>assert.equal(inprocLocate({symbol:''},dir).code,'E_INPROC_ARGUMENT'));
  console.log(JSON.stringify({status:'ok',checks}));
} finally { const resolved=fs.realpathSync(dir); assert.ok(path.basename(resolved).startsWith('ptc-safety-'));fs.rmSync(resolved,{recursive:true,force:true}); }
