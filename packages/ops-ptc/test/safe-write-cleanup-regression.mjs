import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
const require = createRequire(import.meta.url);
const fs = require('node:fs');
const { checkedWrite } = require('../dist/ptc/safe-write.js');
const { inprocRefactor } = require('../dist/ptc/inproc.js');
const dir = fs.realpathSync(fs.mkdtempSync(join(tmpdir(), 'ptc-cleanup-')));
const file = join(dir, 'fixture.ts');
const original = Buffer.from('export const a = 1;\n');
const after = 'export const a = 2;\n';
const native = { unlinkSync: fs.unlinkSync, closeSync: fs.closeSync, writeFileSync: fs.writeFileSync };
let checks = 0;
try {
  fs.writeFileSync(file, original);
  fs.unlinkSync = path => { if (path === `${file}.ops-ptc.lock`) throw Object.assign(new Error('injected lock cleanup failure'), { code: 'EPERM' }); return native.unlinkSync(path); };
  const receipt = checkedWrite(file, original, after);
  assert.equal(fs.readFileSync(file, 'utf8'), after);
  assert.equal(receipt.cleanupErrors.length, 1);
  assert.match(receipt.cleanupErrors[0], /EPERM/);
  checks++;
  fs.unlinkSync = native.unlinkSync;
  fs.unlinkSync(`${file}.ops-ptc.lock`);
  fs.writeFileSync(file, original);
  const primary = Object.assign(new Error('injected primary write failure'), { code: 'ENOSPC' });
  const attempted = [];
  fs.writeFileSync = (fd, ...args) => { if (typeof fd === 'number') throw primary; return native.writeFileSync(fd, ...args); };
  fs.unlinkSync = path => { attempted.push(path); if (String(path).endsWith('.tmp')) throw Object.assign(new Error('injected temp cleanup failure'), { code: 'EACCES' }); return native.unlinkSync(path); };
  assert.throws(() => checkedWrite(file, original, after), e => e === primary && e.cleanupErrors?.some(x => x.includes('EACCES')));
  assert(attempted.includes(`${file}.ops-ptc.lock`), 'lock cleanup attempted even if temp unlink fails');
  assert.equal(fs.existsSync(`${file}.ops-ptc.lock`), false);
  assert(fs.readFileSync(file).equals(original));
  checks++;
  fs.writeFileSync(file, original);
  const inprocPrimary = Object.assign(new Error('injected inproc write failure'), { code: 'ENOSPC' });
  fs.writeFileSync = (fd, ...args) => { if (typeof fd === 'number') throw inprocPrimary; return native.writeFileSync(fd, ...args); };
  const outcome = inprocRefactor({ file, pattern: '1', rewrite: '2', mode: 'apply' }, dir);
  assert.equal(outcome.status, 'error');
  assert.equal(outcome.code, 'ENOSPC');
  assert(outcome.cleanupErrors?.some(x => x.includes('EACCES')), 'public outcome retains cleanup errors attached to the primary failure');
  assert(fs.readFileSync(file).equals(original));
  checks++;
  console.log(JSON.stringify({ status: 'ok', checks, coverage: 'post-commit cleanup receipt; original precommit failure retained; later cleanup not skipped; public error outcome includes attached cleanup errors' }));
} finally {
  Object.assign(fs, native);
  assert.equal(fs.realpathSync(dir), dir);
  fs.rmSync(dir, { recursive: true, force: true });
}
